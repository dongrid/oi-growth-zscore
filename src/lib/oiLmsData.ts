export type OiType = "I" | "III" | "IV";
export type Measure = "height" | "weight";

export interface LmsRow {
  age: number;
  L: number;
  M: number;
  S: number;
}

type Row = [number, number, number, number];

function toRows(data: Row[]): LmsRow[] {
  return data.map(([age, L, M, S]) => ({ age, L, M, S }));
}

